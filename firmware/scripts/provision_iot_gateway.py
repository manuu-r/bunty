"""Explicitly provision a gateway credential during an ESP-IDF flash.

The credential is generated by iot-gateway's device CLI, stored remotely in
Cloudflare D1 as a hash, and written only to Bunty's ignored .pio directory.
After a successful upload, the staged credential is promoted and the previous
credential is retired. A failed upload leaves the previous credential valid.
"""

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess

DEVICE_ID = "bunty"
TOKEN_PATTERN = re.compile(r"^iot_[A-Za-z0-9_-]{43}$")
PROJECT_DIR = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = PROJECT_DIR.parent
GATEWAY_DIR = REPOSITORY_ROOT / "iot-gateway"
DEVICE_SCRIPT = GATEWAY_DIR / "scripts" / "devices.mjs"
GENERATED_DIR = PROJECT_DIR / ".pio" / "generated"
CREDENTIAL_HEADER = GENERATED_DIR / "IotGatewayCredentials.generated.h"
ACTIVATION_MARKER = GENERATED_DIR / "iot_gateway_activation_pending"


def gateway_command(action, token_only=False):
    node = shutil.which("node")
    if not node:
        raise RuntimeError("Node.js is required to provision the IoT Gateway credential")
    if not DEVICE_SCRIPT.is_file():
        raise RuntimeError(
            f"IoT Gateway device script not found at {DEVICE_SCRIPT}. "
            "Keep iot-gateway at the repository root."
        )

    command = [
        node,
        str(DEVICE_SCRIPT),
        action,
        DEVICE_ID,
        "--remote",
    ]
    if token_only:
        command.append("--token-only")

    result = subprocess.run(
        command,
        cwd=GATEWAY_DIR,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
        env={**os.environ, "NO_COLOR": "1"},
    )
    if result.returncode != 0:
        details = "\n".join(
            part.strip() for part in (result.stdout, result.stderr) if part.strip()
        )
        raise RuntimeError(
            f"IoT Gateway '{action}' failed.\n{details}" if details else
            f"IoT Gateway '{action}' failed with exit code {result.returncode}."
        )
    return result.stdout.strip()

def write_credential_header(token):
    if token and not TOKEN_PATTERN.fullmatch(token):
        raise RuntimeError("IoT Gateway returned an invalid device token")

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    temporary_header = CREDENTIAL_HEADER.with_suffix(".tmp")
    temporary_header.write_text(
        "#pragma once\n"
        f'#define IOT_GATEWAY_DEVICE_ID "{DEVICE_ID}"\n'
        f'#define IOT_GATEWAY_TOKEN "{token}"\n',
        encoding="utf-8",
    )
    try:
        temporary_header.chmod(0o600)
    except OSError:
        pass
    temporary_header.replace(CREDENTIAL_HEADER)


def main():
    parser = argparse.ArgumentParser(description="Stage, flash and activate Bunty's gateway credential.")
    parser.add_argument("--port", required=True, help="ESP32-S3 serial port")
    parser.add_argument("--monitor", action="store_true", help="Monitor after successful activation")
    args = parser.parse_args()
    if ACTIVATION_MARKER.exists():
        gateway_command("activate")
        ACTIVATION_MARKER.unlink()
        print("[iot-gateway] completed activation from the previous flash")
    token = gateway_command("stage", token_only=True)
    write_credential_header(token)
    print("[iot-gateway] staged a credential in the ignored generated directory")
    # Do not put monitor in this invocation: it blocks until the user quits,
    # whereas the new credential should activate immediately after flashing.
    subprocess.run([str(PROJECT_DIR / "scripts" / "idf.sh"), "-p", args.port, "flash"],
                   cwd=PROJECT_DIR, check=True)
    ACTIVATION_MARKER.write_text("bunty\n", encoding="utf-8")
    gateway_command("activate")
    ACTIVATION_MARKER.unlink()
    print("[iot-gateway] activated the flashed credential")
    if args.monitor:
        subprocess.run([str(PROJECT_DIR / "scripts" / "idf.sh"), "-p", args.port, "monitor"],
                       cwd=PROJECT_DIR, check=True)


if __name__ == "__main__":
    try:
        main()
    except (OSError, subprocess.SubprocessError, RuntimeError) as error:
        print(f"[iot-gateway] {error}")
        raise SystemExit(1)
